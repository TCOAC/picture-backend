CREATE TABLE IF NOT EXISTS user (
 id BIGINT PRIMARY KEY, userAccount VARCHAR(256) NOT NULL UNIQUE, userPassword VARCHAR(512) NOT NULL,
 userName VARCHAR(256), userAvatar VARCHAR(1024), userProfile VARCHAR(512), userRole VARCHAR(256) DEFAULT 'user' NOT NULL,
 editTime TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, createTime TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 updateTime TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, isDelete INT DEFAULT 0 NOT NULL, vipExpireTime TIMESTAMP,
 vipCode VARCHAR(128), vipNumber BIGINT, shareCode VARCHAR(256), inviteUser BIGINT
);
CREATE TABLE IF NOT EXISTS vip_code (
 codeHash CHAR(64) PRIMARY KEY, durationDays INT NOT NULL, createdBy BIGINT NOT NULL,
 createTime TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, redeemedBy BIGINT, redeemedAt TIMESTAMP
);
CREATE TABLE IF NOT EXISTS space (
 id BIGINT PRIMARY KEY, spaceName VARCHAR(128) NOT NULL, spaceLevel INT NOT NULL DEFAULT 0, spaceType INT NOT NULL DEFAULT 0,
 userId BIGINT NOT NULL, maxSize BIGINT NOT NULL, maxCount BIGINT NOT NULL, totalSize BIGINT NOT NULL DEFAULT 0,
 totalCount BIGINT NOT NULL DEFAULT 0, createTime TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 updateTime TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, isDelete INT DEFAULT 0 NOT NULL
);
CREATE TABLE IF NOT EXISTS space_user (
 id BIGINT PRIMARY KEY, spaceId BIGINT NOT NULL, userId BIGINT NOT NULL, spaceRole VARCHAR(16) NOT NULL DEFAULT 'viewer',
 createTime TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, UNIQUE(spaceId,userId)
);
CREATE TABLE IF NOT EXISTS picture (
 id BIGINT PRIMARY KEY, url VARCHAR(2048) NOT NULL, name VARCHAR(128) NOT NULL, introduction VARCHAR(800), category VARCHAR(64),
 tags VARCHAR(1024) DEFAULT '[]', picSize BIGINT NOT NULL, picWidth INT NOT NULL, picHeight INT NOT NULL, picScale DOUBLE,
 picFormat VARCHAR(16), fileHash VARCHAR(64), perceptualHash VARCHAR(16), picColor VARCHAR(16), spaceId BIGINT,
 userId BIGINT NOT NULL, reviewStatus INT NOT NULL DEFAULT 0, reviewMessage VARCHAR(512), reviewerId BIGINT, reviewTime TIMESTAMP,
 shareCode VARCHAR(64), shareExpireTime TIMESTAMP, viewCount BIGINT NOT NULL DEFAULT 0, downloadCount BIGINT NOT NULL DEFAULT 0,
 createTime TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, editTime TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 updateTime TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, isDelete INT DEFAULT 0 NOT NULL
);
